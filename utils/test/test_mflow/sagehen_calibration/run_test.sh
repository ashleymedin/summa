#!/bin/bash
# ---------------------------------------------------------------------------------------
# Coupled SUMMA / MODFLOW 6 / mizuRoute calibration on lumped Sagehen Creek, against every kind of
# target and through every MODFLOW package the coupler drives.
#
# The domain (9 GRUs, each a land and a stream HRU) runs MODFLOW with RCH, UZF and UZE, SFR, DRN, the
# base GHB/DRN exchange, EVT and a GWE model, and writes OBS6 heads; mizuRoute routes the 9 reaches.
# It spins up over water year 2017 and scores October-November 2017.
#
#  1. A reference trial with every searched parameter pinned to TRUTH writes the targets
#     (make_targets.py): discharge and temperature at a reach, OBS6 heads pooled over ten cells,
#     domain storage change accumulated, a GRU's aquifer baseflow, and an HRU's aquifer storage as a
#     departure from its mean.
#  2. The same pinned trial, scored against them, must reproduce them.
#  3. A small NSGA-II search over the SUMMA and MODFLOW multipliers must run, and each worker's
#     MODFLOW files must hold its last trial's multipliers.
#
# Needs bin/summa_modflow6_opt_sundials_mizuroute.exe, built with -DUSE_MPI=ON -DUSE_MIZUROUTE=ON
# -DUSE_MODFLOW6=ON, and a python3 with netCDF4.
#
# Usage:  ./run_test.sh [population] [generations] [n_ranks]
# ---------------------------------------------------------------------------------------
set -euo pipefail

TEST_DIR="$(cd "$(dirname "$0")" && pwd)"
SUMMA_ROOT="$(cd "${TEST_DIR}/../../../.." && pwd)"

POPULATION=${1:-4}
GENERATIONS=${2:-2}
N_RANKS=${3:-5}
N_SAMPLES=$((POPULATION * GENERATIONS))
WORK="${TEST_DIR}/run"
PYTHON=${PYTHON:-python3}
SUMMA_EXE="${SUMMA_ROOT}/bin/summa_modflow6_opt_sundials_mizuroute.exe"
REACH=9
GRU=5
HRU=5

# name  truth  lower  upper  scale  what it scales; SUMMA parameters keep their localParamInfo.txt bounds
PARAMS="K_mult        2.0     0.2   5.0   log     files = [\"kh1.txt\", \"kv1.txt\"]
Sy_zone3_mult 0.7     0.5   1.5   linear  files = \"sy1.txt\"|zone_file = \"syzone1.txt\"|zone = 3
rhk_mult      3.0     0.1   10.0  log     files = \"sagehen.sfr\"|block = \"PACKAGEDATA\"|column = 10
vks_mult      0.5     0.1   10.0  log     files = \"sagehen.uzf\"|block = \"PACKAGEDATA\"|column = 8
kts_mult      1.5     0.5   2.0   linear  files = \"kts1.txt\"
k_soil        3.0e-6  -     -     log     summa
k_macropore   1.0e-2  -     -     log     summa"

if [ ! -x "${SUMMA_EXE}" ]; then
  echo "ERROR: ${SUMMA_EXE} not found"
  echo "       build it with -DUSE_MPI=ON -DUSE_MIZUROUTE=ON -DUSE_MODFLOW6=ON"
  exit 1
fi

echo "======================================================================"
echo "SUMMA coupled calibration test (lumped Sagehen, every target kind and MODFLOW package)"
echo "======================================================================"
echo "  executable:  ${SUMMA_EXE}"
echo "  budget:      ${N_SAMPLES} trials (population ${POPULATION} x ${GENERATIONS} generations) on ${N_RANKS} ranks"
echo

rm -rf "${WORK}"
mkdir -p "${WORK}"
cp -r "${TEST_DIR}/domain" "${WORK}/domain"
sed -i.bak "s|^  map_file .*|  map_file           = '${WORK}/domain/hru2cell_map.txt'|" "${WORK}/domain/summa_modflow6.config"

# the reference's settings: the SUMMA parameters' bounds pinned to their true values (the spinup still
# runs at the defaults, as every trial's does), and hourly output of what the targets are made from
cp -r "${WORK}/domain/settings/SUMMA" "${WORK}/domain/settings/SUMMA_ref"
"${PYTHON}" - "${WORK}/domain/settings/SUMMA_ref" "${PARAMS}" <<'PYEOF'
import os, sys
settings, params = sys.argv[1], [l.split() for l in sys.argv[2].splitlines()]
truth = {p[0]: p[1] for p in params if p[5] == "summa"}
path = os.path.join(settings, "localParamInfo.txt")
out = []
for line in open(path):
    key = line.split("|")[0].strip() if "|" in line else ""
    if key in truth:
        line = f"{key:<26}| {line.split('|')[1].strip():>12} | {truth[key]:>12} | {truth[key]:>12}\n"
    out.append(line)
open(path, "w").writelines(out)
with open(os.path.join(settings, "outputControl.txt"), "a") as f:
    for v in ("scalarStreamTemp", "basin__StorageChange", "basin__AquiferBaseflow", "scalarAquiferStorage"):
        f.write(f"{v} | 1\n")
PYEOF

# write_config <dir> <settings> <algorithm> <n_samples> <targets> <pinned>
write_config() {
  local dir=$1 settings=$2 algorithm=$3 samples=$4 targets=$5 pinned=$6
  mkdir -p "${dir}/output" "${dir}/state"
  cp "${WORK}/domain/settings/SUMMA/coldState.nc" "${dir}/state/"
  local write_ts=false
  [ "${pinned}" = "yes" ] && write_ts=true
  {
  cat <<EOF
# generated by run_test.sh

[simulation]

case_name = "sagehen"

# one spinup year (water year 2017) precedes the simulation, which the calibration then scores
start_time = "2017-10-01 01:00"
end_time   = "2017-11-30 23:00"
time_zone  = "utcTime"

use_mizuroute    = true
use_modflow      = true
write_timeseries = ${write_ts}

work_path = "${dir}/output"


[summa_files]

settings_path = "${WORK}/domain/settings/${settings}/"
forcing_path  = "${WORK}/domain/forcing/"
state_path    = "${dir}/state/"
output_path   = "${dir}/output/"

init_condition = "coldState.nc"
attributes     = "attributes.nc"
forcing_list   = "forcingFileList.txt"

decisions        = "modelDecisions.txt"
output_control   = "outputControl.txt"
trial_params     = "trialParams.nc"
local_parameters = "localParamInfo.txt"
basin_parameters = "basinParamInfo.txt"

vegetation_table = "TBL_VEGPARM.TBL"
soil_table       = "TBL_SOILPARM.TBL"
general_table    = "TBL_GENPARM.TBL"
noahmp_table     = "TBL_MPTABLE.TBL"


[modflow]

config_file = "${WORK}/domain/summa_modflow6.config"
run_dir     = "${WORK}/domain/mf6"


[mizuRoute]

namelist_path = "${WORK}/domain/settings/mizuroute/"
namelist_file = "mizuroute.param"

methods = "3"
dt      = 3600

write_qbasin = false
write_Qreach = ${write_ts}


[hydrofabric]

hfabric_path = "${WORK}/domain/"
hfabric_file = "topology.nc"

dname_seg = "seg"
dname_hru = "hru"

varname_HRUid     = "hruId"
varname_segId     = "segId"
varname_hruSegId  = "hruToSegId"
varname_downSegId = "downSegId"

varname_area   = "area"
varname_slope  = "slope"
varname_length = "length"


[calibration]

algorithm = "${algorithm}"

start_date = "2017-10-01"
end_date   = "2017-11-30"

n_samples = ${samples}

param_list = ["k_soil", "k_macropore"]

write_aligned = false


[calibration.parameter_transformations]

EOF
  echo "${PARAMS}" | awk '$5 == "log" {printf "%-13s = \"log\"\n", $1}'
  echo
  echo "${PARAMS}" | awk -v pinned="${pinned}" '
    $6 == "summa" {next}
    {
      lo = (pinned == "yes") ? $2 : $3; hi = (pinned == "yes") ? $2 : $4
      spec = $6; for (i = 7; i <= NF; i++) spec = spec " " $i
      gsub(/\|/, "\n", spec)
      printf "[[calibration.modflow_parameter]]\n\nname = \"%s\"\n%s\nlower = %s\nupper = %s\n\n", $1, spec, lo, hi
    }'
  [ "${algorithm}" = "nsga2" ] && printf "[calibration.nsga2]\n\npopulation_size = %s\n\n" "${POPULATION}"
  cat "${targets}"
  } > "${dir}/config.toml"
}

# run <dir> <ranks>
run() {
  local dir=$1 ranks=$2 status
  set +e
  mpirun -np "${ranks}" "${SUMMA_EXE}" -c "${dir}/config.toml" > "${dir}/run.log" 2>&1
  status=$?
  set -e
  if [ ${status} -ne 0 ]; then
    echo "FAIL: ${dir} exited ${status}"
    tail -25 "${dir}/run.log"
    exit 1
  fi
}

# every kind of target, from the reference trial's series
OBS="${WORK}/targets/sagehen_targets_daily.nc"
OBS_CELLS=$(awk '/HEAD/ {print $1}' "${WORK}/domain/mf6/sagehen.obs")
names=$(for c in ${OBS_CELLS}; do printf '"%s", ' "$c"; done | sed 's/, $//')
vnames=$(for c in ${OBS_CELLS}; do printf '"h_%s", ' "$c"; done | sed 's/, $//')
target() {  # target <name> <metric> <variable> <obs variable> [extra lines]
  printf '[[calibration.target]]\n\nname      = "%s"\nmetric    = "%s"\nvariable  = "%s"\nvname_obs = %s\nobs_path  = "%s/"\nobs_file  = "%s"\n%s\n\n' \
         "$1" "$2" "$3" "$4" "$(dirname "${OBS}")" "$(basename "${OBS}")" "${5:-}"
}
{
  target discharge          kge  streamflow             '"q_obs"'        "reach = ${REACH}"
  target stream_temperature rmse T_reach                '"t_obs"'        "reach = ${REACH}"
  target heads              rmse modflow_obs            "[${vnames}]"    "obs_name = [${names}]"
  target storage            rmse basin__StorageChange   '"storage_obs"'  "accumulate = true"
  target baseflow           kge  basin__AquiferBaseflow '"baseflow_obs"' "gru = ${GRU}"
  target aquifer            rmse scalarAquiferStorage   '"aquifer_obs"'  "hru = ${HRU}
baseline_start = \"2017-10-01\"
baseline_end   = \"2017-11-30\""
} > "${WORK}/targets.toml"
# the reference trial is scored against the gauge, only so it runs as a calibration trial does
mkdir -p "${WORK}/targets"
cat > "${WORK}/placeholder.toml" <<EOF
[[calibration.target]]

name      = "discharge"
variable  = "streamflow"
reach     = ${REACH}
obs_path  = "${TEST_DIR}/"
obs_file  = "USGS_10343500_daily_flow.nc"
vname_obs = "q_obs"
metric    = "kge"
EOF

echo "Running the reference trial at the true parameters..."
write_config "${WORK}/reference" SUMMA_ref dds 1 "${WORK}/placeholder.toml" yes
run "${WORK}/reference" 2
"${PYTHON}" "${TEST_DIR}/make_targets.py" \
  "$(ls "${WORK}"/reference/output/*_sample000001_timestep.nc)" \
  "${WORK}/reference/output/modflow_rank0001/sagehen.obs.csv" \
  "${WORK}/domain/settings/SUMMA/attributes.nc" ${REACH} ${GRU} ${HRU} "${OBS}"
echo

echo "Scoring the true parameters against the targets..."
write_config "${WORK}/truth" SUMMA_ref dds 1 "${WORK}/targets.toml" yes
run "${WORK}/truth" 2
echo

echo "Running nsga2..."
write_config "${WORK}/search" SUMMA nsga2 "${N_SAMPLES}" "${WORK}/targets.toml" no
run "${WORK}/search" "${N_RANKS}"
grep -E "^NSGA-II generation" "${WORK}/search/run.log" | sed 's/^/  /' || true
echo

echo "Checking..."
"${PYTHON}" "${TEST_DIR}/check_test.py" "${WORK}" "${PARAMS}" "${POPULATION}" "${GENERATIONS}"

echo
echo "PASS"
